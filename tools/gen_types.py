"""``make gen-types`` step 1: dump JSON Schema for every exported pydantic model, and the API's
OpenAPI document (production surface: OIDC auth, so no dev routes).

Step 2 (web/scripts/gen-types.mjs) turns both into TypeScript under ``web/src/types/generated``
(``index.ts`` message types, ``api.ts`` REST paths for the ``openapi-fetch`` client). Never
hand-edit the generated files.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

from galecore.schemas import SCHEMA_VERSION, json_schemas

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "web" / "src" / "types" / "generated" / "schemas.json"
OPENAPI = OUT.with_name("openapi.json")


def openapi() -> dict[str, object]:
    from gale_api.app import build_app
    from galecore.config import Settings

    s = Settings(env="test", bus_backend="memory", auth_mode="oidc", workers=False)
    spec = build_app(s).openapi()
    spec["info"]["description"] = "GENERATED by `make gen-types` from services/api. Do not edit."
    return spec


def bundle() -> dict[str, object]:
    return {
        "$comment": "GENERATED by `make gen-types` from packages/galecore/schemas.py. Do not edit.",
        "schema_version": SCHEMA_VERSION,
        "models": json_schemas(),
    }


def main() -> int:
    OUT.parent.mkdir(parents=True, exist_ok=True)
    text = json.dumps(bundle(), indent=2, ensure_ascii=False, sort_keys=True) + "\n"
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT).as_posix()}", file=sys.stderr)
    api = json.dumps(openapi(), indent=2, ensure_ascii=False, sort_keys=True) + "\n"
    OPENAPI.write_text(api, encoding="utf-8", newline="\n")
    print(f"wrote {OPENAPI.relative_to(ROOT).as_posix()}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
