// `make gen-types` step 2: JSON Schema bundle → TypeScript (index.ts) and the API's OpenAPI
// document → path types for openapi-fetch (api.ts). Never hand-edit the output.
import { readFile, writeFile } from "node:fs/promises";
import { compile } from "json-schema-to-typescript";
import openapiTS, { astToString } from "openapi-typescript";

const dir = new URL("../src/types/generated/", import.meta.url);
const bundle = JSON.parse(await readFile(new URL("schemas.json", dir), "utf8"));

// pydantic titles every property, which would make one TS alias per field (CallId1, TsEnd2…).
// Keep titles only on named definitions (models and enums).
function stripPropertyTitles(node) {
  if (Array.isArray(node)) return node.map(stripPropertyTitles);
  if (node === null || typeof node !== "object") return node;
  const out = {};
  for (const [k, v] of Object.entries(node)) {
    if (k === "properties") {
      out[k] = Object.fromEntries(
        Object.entries(v).map(([p, s]) => {
          const rest = { ...s };
          delete rest.title;
          return [p, stripPropertyTitles(rest)];
        }),
      );
    } else {
      out[k] = stripPropertyTitles(v);
    }
  }
  return out;
}

// Merge every model and its $defs into one schema so shared enums are declared once.
const defs = {};
for (const [name, schema] of Object.entries(bundle.models)) {
  const { $defs = {}, ...rest } = stripPropertyTitles(schema);
  Object.assign(defs, $defs);
  defs[name] = rest;
}
const root = {
  title: "GaleSchemas",
  type: "object",
  additionalProperties: false,
  properties: Object.fromEntries(
    Object.keys(bundle.models).map((n) => [n, { $ref: `#/$defs/${n}` }]),
  ),
  $defs: defs,
};

const banner =
  "/* GENERATED by `make gen-types` from packages/galecore/schemas.py " +
  `(schema v${bundle.schema_version}). Do not edit. */`;
const ts = await compile(root, "GaleSchemas", {
  bannerComment: banner,
  unreachableDefinitions: true,
  additionalProperties: false,
  strictIndexSignatures: true,
  style: { singleQuote: false, printWidth: 100 },
});
await writeFile(new URL("index.ts", dir), ts.replace(/\r\n/g, "\n"));
console.error("wrote web/src/types/generated/index.ts");

const spec = JSON.parse(await readFile(new URL("openapi.json", dir), "utf8"));
const apiBanner = "/* GENERATED by `make gen-types` from services/api (OpenAPI). Do not edit. */";
const apiTs = `${apiBanner}\n${astToString(await openapiTS(spec, { alphabetize: true }))}`;
await writeFile(new URL("api.ts", dir), apiTs.replace(/\r\n/g, "\n"));
console.error("wrote web/src/types/generated/api.ts");
